"""
Build the scenario manifest from scripts/scenarios/*.yaml.

The manifest is the single source of truth for WACC, NDC status, gas
price, group label, and colour per scenario. It is generated by
parsing the scenario YAMLs, so it cannot drift from the actual runs.
"""
from __future__ import annotations

import re
from dataclasses import dataclass, asdict
from pathlib import Path

import pandas as pd
import yaml


SCEN_DIR = Path("scripts/scenarios")


@dataclass
class Scenario:
    run_name: str          # e.g. "config.nigeria.2030_C1_wacc_0700"
    filename: str          # e.g. "config.nigeria.2030_C1_wacc_0700.yaml"
    group: str             # "B", "C", "D", "P-a", "P-b", "S"
    wacc_solar: float
    wacc_battery: float
    wacc_gas: float
    ndc: bool
    gas_usd_per_mmbtu: float
    label: str             # human-readable, for figures
    order: int             # plotting order


def _parse_yaml(path: Path) -> dict:
    return yaml.safe_load(path.read_text()) or {}


def _group_from_name(fname: str) -> str:
    if fname.startswith("cap_exp_2030_uniform"):
        return "B"
    if fname.startswith("cap_exp_2030_split"):
        return "B"
    if "_B3_" in fname:
        return "B"
    if "_C" in fname and "_wacc" in fname:
        return "C"
    if "_D" in fname and "_ndc" in fname:
        return "D"
    if "_P1_" in fname or "_P1D_" in fname:
        return "P-b"
    if "_P2_" in fname or "_P3_" in fname or "_P4_" in fname:
        return "P-a"
    if "_S2a_" in fname or "_S2b_" in fname:
        return "S"
    return "?"


def _gas_price_from_name(fname: str) -> float:
    if "gas_600" in fname:
        return 6.00
    return 3.39


def _label(fname: str, group: str, wacc_solar: float, ndc: bool) -> str:
    """Short human-readable label for figure legends."""
    base = fname.replace(".yaml", "")
    # Strip common prefixes
    base = base.replace("cap_exp_2030_", "").replace("config.nigeria.2030_", "")
    tag = ""
    if ndc:
        tag = " +NDC"
    return f"{base}{tag}"


def _order(group: str, wacc_solar: float, ndc: bool) -> int:
    """Plot ordering: group first, then WACC, then NDC."""
    group_rank = {"B": 0, "C": 1, "D": 2, "P-a": 3, "P-b": 4, "S": 5}.get(group, 9)
    ndc_rank = 1 if ndc else 0
    return int(group_rank * 10000 + wacc_solar * 1000 + ndc_rank)


def build_manifest(scen_dir: Path = SCEN_DIR) -> pd.DataFrame:
    """Return a DataFrame with one row per scenario."""
    rows = []
    for yaml_path in sorted(scen_dir.glob("*.yaml")):
        cfg = _parse_yaml(yaml_path)
        if "run" not in cfg or "name" not in cfg["run"]:
            continue  # not a scenario file
        run_name = cfg["run"]["name"]

        costs = cfg.get("costs") or {}
        groups = costs.get("discountrate_groups") or {}

        def rate(group):
            g = groups.get(group)
            return float(g["rate"]) if isinstance(g, dict) and "rate" in g else None

        wacc_solar = rate("renewable")
        wacc_battery = rate("battery")
        wacc_gas = rate("fossil")

        # Fall back to top-level discountrate if group missing
        if wacc_solar is None:
            dr = costs.get("discountrate")
            wacc_solar = float(dr[0]) if isinstance(dr, list) else float(dr) if dr else None

        ndc = cfg.get("co2", {}).get("limit") not in (None, "null")

        gas_usd = _gas_price_from_name(yaml_path.name)
        group = _group_from_name(yaml_path.name)

        rows.append(asdict(Scenario(
            run_name=run_name,
            filename=yaml_path.name,
            group=group,
            wacc_solar=wacc_solar,
            wacc_battery=wacc_battery,
            wacc_gas=wacc_gas,
            ndc=ndc,
            gas_usd_per_mmbtu=gas_usd,
            label=_label(yaml_path.name, group, wacc_solar, ndc),
            order=_order(group, wacc_solar or 0, ndc),
        )))

    df = pd.DataFrame(rows).sort_values(["order"]).reset_index(drop=True)
    return df


def write_manifest(out_path: Path = Path("analysis/manifest.csv")) -> pd.DataFrame:
    df = build_manifest()
    out_path.parent.mkdir(parents=True, exist_ok=True)
    df.to_csv(out_path, index=False)
    return df


if __name__ == "__main__":
    df = write_manifest()
    print(f"Wrote {len(df)} scenarios to analysis/manifest.csv")
    print(df[["run_name", "group", "wacc_solar", "wacc_gas", "ndc",
              "gas_usd_per_mmbtu"]].to_string(index=False))
